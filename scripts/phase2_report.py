"""
Phase 2 - turn the graph metrics into a readable findings document.

Computation lives in scripts/analyse_graph.py; this module is the writing. They
are separate so that the numbers cannot be quietly adjusted while prose is being
tuned around them.

Every metric is reported with what it means and what it cannot mean here. The
graph is in seventeen pieces, and several standard measures return values that
look impressive and say nothing on a graph of that shape. Those are called out
where they occur, because the point of the section is to be defensible.

Usage:  python scripts/phase2_report.py
"""

import json
import sqlite3
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))

from analyse_graph import (  # noqa: E402
    DB, comparative, communities, hubs, load_graph, loops, placement_layer, shape,
    typology, verification_state,
)

OUT = ROOT / "docs" / "phase2"



def num_word(n):
    """Spell out small counts, which read better at the start of a sentence."""
    words = ["zero", "one", "two", "three", "four", "five", "six", "seven", "eight",
             "nine", "ten"]
    return words[n] if 0 <= n < len(words) else str(n)

def fmt(value):
    return "not stated" if value is None else f"{value:,.2f}"


def write_findings(m, path):
    v = m["verification"]
    pending = v["counts"].get("pending", 0)
    total_edges = sum(v["counts"].values())
    s, h, c = m["shape"], m["hubs"], m["loops"]
    comm, comp = m["communities"], m["comparative"]

    md = [
        "# Phase 2: network construction and analysis",
        "",
        f"Evidence base `{v['version']}`. Generated by `scripts/phase2_report.py`; "
        "regenerate with `python run_all.py`.",
        "",
    ]
    if pending:
        md += [
            f"> **Unverified.** {pending} of the {total_edges} edges have not been "
            "checked against their source by hand. Every figure below is provisional "
            "and is recomputed as decisions are recorded in `data/verification.csv`. "
            "See [../review/](../review/).",
            "",
        ]
    md += [
        "Inferred edges are excluded throughout. Counts are split by whether the source "
        "named the counterparty or only described it.",
        "",
        "---",
        "",
        "## 0. What shape is this graph, and what can it therefore support?",
        "",
        f"- **{s['nodes']} nodes**, **{s['edges']} edges**, "
        f"**{s['components']} connected components**",
        f"- component sizes: {', '.join(str(n) for n in s['component_sizes'])}",
        f"- density {s['density']}",
        "",
        "This governs everything below. The public record does not describe one "
        f"insider network behind the 23 failures. It describes {s['components']} "
        f"separate structures, the largest holding {s['component_sizes'][0]} entities.",
        "",
        "The two largest are the cases worth telling in full:",
        "",
    ]
    for members in s["largest_components"]:
        md.append(f"- {', '.join(members)}")

    md += [
        "",
        "---",
        "",
        "## 1. Hub detection: does anyone connect more than one failed institution?",
        "",
        "**Degree centrality** counts how many connections a node has. **Betweenness "
        "centrality** counts how often it lies on the shortest path between two other "
        "nodes. That is the broker measure, and the one that would identify a person or "
        "company bridging separate failures.",
        "",
        f"**Betweenness is zero for all but {h['nonzero_betweenness']} of the "
        f"{s['nodes']} nodes** (highest {h['max_betweenness']}). That is not a finding "
        "about Ghana's savings and loans sector; it is a property of a graph in "
        "seventeen pieces. A node inside a three-node component can lie between almost "
        "nothing, so the measure has nothing to measure. A betweenness ranking drawn "
        "from this graph would be a number presented as an insight.",
        "",
        "Degree is meaningful within a component, and is reported:",
        "",
        "| entity | type | degree |",
        "|---|---|---|",
    ]
    for row in h["top_degree"][:8]:
        md.append(f"| {row['name']} | `{row['type']}` | {row['degree']} |")

    md += [
        "",
        "**The question the project was set to answer.** Does any entity connect two "
        "or more of the 23 institutions?",
        "",
    ]
    if h["connect_multiple_institutions"]:
        for node, insts in sorted(h["connect_multiple_institutions"].items()):
            md.append(f"- **{node}**: {', '.join(insts)}")
        md += ["", "Each is a candidate for a case walkthrough."]
    else:
        md += [
            "**No entity in the public record connects two or more of the 23.** Every "
            "named counterparty, holding company and unnamed related-party group in "
            "the evidence base attaches to exactly one institution.",
            "",
            "This is a real result and belongs in the open rather than buried. It does "
            "not mean no such entity exists. It means the revocation notice does not "
            "name one, and the notice was written to explain why each institution "
            "failed, not to map ownership across them. Establishing whether the same "
            "people sit behind several failures needs registry or court data, which "
            "the limitations set out.",
        ]

    md += [
        "",
        "---",
        "",
        "## 2. Closed loops: does ownership or lending fold back on itself?",
        "",
        "A **cycle** is a path returning to where it began. In a related-party "
        "structure it is the signature worth looking for: value leaves an institution "
        "and control over it returns, or two institutions fund each other. Direction "
        "matters, so this runs on the directed graph.",
        "",
        f"**Cycles found: {c['count']}. Of those, closed loops where every leg moves "
        f"value: {c['circular_funding_loops']}.**",
        "",
        "These are named *circular funding* rather than *extraction* loops, which is "
        "the weaker and more accurate word. A leg marked as moving value says the "
        "relationship moves money; it does not say the money left one of the 23. In "
        "the one case below it moves both ways: out of the institution to a related "
        "party, and back in from that party's client funds. That is circular funding "
        "between related parties. Whether either side ended up better off is a "
        "question these documents do not answer.",
        "",
    ]
    if c["cycles"]:
        for cyc in c["cycles"]:
            md.append(f"- {' → '.join(cyc['members'] + [cyc['members'][0]])}")
            for leg in cyc["legs"]:
                mark = "moves value" if leg["extracts_value"] else "**does not move value**"
                md.append(f"    - {leg['from']} → {leg['to']}: "
                          f"`{'`, `'.join(leg['relationships'])}`, {mark}")
            md.append("")
        if not c["circular_funding_loops"]:
            md += [
                "**None of these is a closed extraction loop.** In each, at least one "
                "leg is a relationship that does not move value, so the arrows return "
                "to their origin without the money doing so.",
                "",
                "The distinction is the whole point. Ideal Finance carried "
                "related-party exposure to FirsTrust, and FirsTrust appears to point "
                "back only because the two applied to merge. A merger application is "
                "a corporate action, not a payment. Counting that as circular "
                "extraction would be the kind of claim this project exists to avoid. "
                "The cycle is real; its interpretation as value recycling is not.",
            ]
        else:
            md += [
                "The loops marked as moving value on every leg are the circular funding "
                "described above, and each has a case walkthrough of its own.",
            ]
    else:
        md += [
            "None. The documented structures are stars and trees, not loops. Value "
            "leaves an institution towards a related party and no edge in the record "
            "brings it back.",
            "",
            "The nearest thing is the Ideal Financial Holdings structure, a common "
            "owner above two institutions that lent to each other. That is the "
            "pattern the project was looking for, and it is worth being precise about "
            "why it is not a cycle: the ownership edges point down from the holding "
            "company to both institutions, so the arrows never close. The structure "
            "is real; the word for it is a shared parent with cross-lending, not a "
            "closed loop.",
        ]

    md += [
        "",
        "---",
        "",
        "## 3. Community detection: do clusters share owners or counterparties?",
        "",
        "**Community detection** looks for groups more densely connected to each other "
        "than to the rest of the graph. **Modularity** scores how well a division "
        "separates it, from 0 (no better than random) towards 1.",
        "",
        f"- components: {comm['components']}",
        f"- communities detected: {comm['communities_detected']}",
        f"- modularity: {comm['modularity']}",
        "",
    ]
    if comm["communities_equal_components"]:
        md += [
            "**The communities detected are exactly the connected components.** The "
            "algorithm found nothing the component structure had not already given, "
            "which is what happens on a disconnected graph: there is no "
            "denser-than-average grouping to find inside a three-node star.",
            "",
            f"The modularity of {comm['modularity']} is high, and presenting it as a "
            "strong result would be the easiest mistake available with this dataset. "
            "Modularity is high *because* the graph is fragmented. A partition into "
            "disconnected pieces always scores well, since no edge crosses between "
            "them. Here it measures the fragmentation, not the discovery of community "
            "structure. It is recorded so the mistake is not made later.",
        ]
    else:
        md += [
            "The detected communities differ from the connected components, so the "
            "algorithm split at least one component into denser sub-groups. Those "
            "splits are worth examining individually before anything is claimed.",
        ]

    a, b = comp["flagged_related_party"], comp["not_flagged"]
    md += [
        "",
        "---",
        "",
        "## 4. Comparative structure: do the 17 differ from the other 6?",
        "",
        "`ghana-banking-collapse` flagged 17 of the 23 for related-party exposure. "
        "The question is whether that flag corresponds to anything structural.",
        "",
        f"| | flagged ({a.get('institutions')}) | not flagged ({b.get('institutions')}) |",
        "|---|---|---|",
    ]
    for label, key in (
            ("institutions", "institutions"),
            ("with any edge", "with_any_edge"),
            ("with a value-moving edge", "with_value_extracting_edge"),
            ("value-moving edges out, total", "total_value_extracting_edges"),
            ("with a named counterparty", "with_a_named_counterparty"),
            ("with a stated amount", "institutions_with_an_amount"),
            ("median cause count", "median_cause_count")):
        md.append(f"| {label} | {a.get(key, 'not stated')} | {b.get(key, 'not stated')} |")
    md += [
        f"| quantified exposure, GHS m | {fmt(a.get('quantified_ghs_m'))} "
        f"| {fmt(b.get('quantified_ghs_m'))} |",
        "",
        ("**The groups separate cleanly.** Every institution carrying a "
         "value-moving edge out is one of the flagged "
         f"{a.get('institutions')}, and none outside them carries one."
         if b.get("with_value_extracting_edge") == 0
         and a.get("with_value_extracting_edge") == a.get("institutions")
         else "**The groups do not separate cleanly.** "
              f"{b.get('with_value_extracting_edge')} unflagged institution(s) carry a "
              f"value-moving edge out, and {a.get('institutions', 0) - a.get('with_value_extracting_edge', 0)} "
              "flagged institution(s) carry none."),
        "",
        "**This is a consistency check, not a confirmation, and the distinction "
        "matters.** The flag comes from `ghana-banking-collapse`, which coded it from "
        "the Bank of Ghana notice of 16 August 2019. The edges were extracted from "
        "the same notice. Two readings of one document agreeing is evidence that the "
        "extraction pipeline neither dropped an institution nor invented one, which "
        "is worth knowing and is why it is reported, but it is not a second source "
        "corroborating the first. A perfect separation here was close to guaranteed "
        "by where both variables come from, and it should not be read as the graph "
        "validating the published count.",
        "",
        "What it does **not** show is a difference in connectedness. Outside the two "
        "case networks, almost every institution's related parties attach only to it, "
        "so there is no structural distance to measure between the groups.",
        "",
        "### Per institution",
        "",
        "| institution | flagged | edges out | value-moving | counterparties | named | unnamed | GHS m |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for r in comp["rows"]:
        md.append(
            f"| {r['name']} | {'yes' if r['flagged'] else 'no'} | {r['edges_out']} "
            f"| {r['value_extracting']} | {r['counterparties']} | {r['named']} "
            f"| {r['unnamed']} | {fmt(r['extracted_ghs_m'])} |")

    md += [
        "",
        "---",
        "",
        "## 5. The mechanisms, counted, and which way value moved",
        "",
        "Each edge carries a relationship from a controlled vocabulary, and each "
        "relationship is marked for whether value moves along it. This part of the "
        "analysis does not depend on connectivity, and on this evidence base it "
        "carries more weight than the network measures do.",
        "",
        "**Direction is reported separately from the flag, because they are different "
        "things.** `extracts_value` says money moves along the relationship. It does "
        "not say the money left one of the 23: a fund manager placing client funds in "
        "an institution moves value *into* it, and a fund manager placing them with "
        "its own related company involves none of the 23 at all. Only the "
        "`from_institution` rows below describe value leaving a failed institution.",
        "",
        "| direction | category | relationship | moves value | edges | counterparty named |",
        "|---|---|---|---|---|---|",
    ]
    order = {"from_institution": 0, "into_institution": 1, "between_third_parties": 2}
    for row in sorted(m["typology"],
                      key=lambda r: (order.get(r["direction"], 9), r["category"],
                                     -r["edges"], r["relationship"])):
        md.append(f"| `{row['direction']}` | {row['category']} | "
                  f"`{row['relationship']}` | "
                  f"{'yes' if row['extracts_value'] else 'no'} | {row['edges']} "
                  f"| {row['named_counterparty']} |")
    out_of = sum(r["edges"] for r in m["typology"]
                 if r["direction"] == "from_institution" and r["extracts_value"])
    other = sum(r["edges"] for r in m["typology"]
                if r["direction"] != "from_institution" and r["extracts_value"])
    md += [
        "",
        f"**{out_of} relationships move value out of one of the 23.** A further "
        f"{other} move value along a related-party relationship pointing the other "
        "way, or between two parties neither of which is one of the 23. The second "
        "group is mostly fund managers placing their clients' money with their own "
        "related companies, which is the Commission's finding about those firms "
        "rather than this project's finding about the 23.",
    ]

    pl = m["placement_layer"]
    ifa = pl["if_admitted"]
    md += [
        "",
        "---",
        "",
        "## 6. The placement layer, and why it is kept out of the figures above",
        "",
        "The Securities and Exchange Commission notice describes a second kind of "
        "relationship that the Bank of Ghana notice does not: a fund manager placing "
        "client money in one of the 23, with no related-party claim attached. Value "
        "moves. No insider relationship is alleged.",
        "",
        f"There are **{pl['edges']} such edges**, from **{pl['fund_managers']} fund "
        f"managers**, reaching **{pl['institutions_reached']} of the 23**. They are "
        "held in a separate layer, marked `placement` in `relationship_types`, "
        "filtered out of `v_institution_profile`, and excluded from every figure in "
        "sections 0 to 5.",
        "",
        "**What that separation is worth, as a number.** "
        f"{num_word(len(pl['managers_reaching_more_than_one'])).capitalize()} of the "
        f"{num_word(pl['fund_managers'])} fund managers name more than one of the 23. Admitting "
        "these as ordinary edges would take the graph from "
        f"**{ifa['components_related_party_only']} components, largest "
        f"{ifa['largest_component_related_party_only']}**, to "
        f"**{ifa['components_if_admitted']} components, largest "
        f"{ifa['largest_component_if_admitted']}**, a single structure holding most "
        "of the graph. That structure would be real, but it would not be an insider "
        "network. It would be a set of institutions that happen to share a fund "
        "manager who placed client money in both, which is a different fact and a "
        "weaker one.",
        "",
        "| institution | fund managers placing client funds there |",
        "|---|---|",
    ]
    for name, managers in sorted(pl["institutions_with_more_than_one_manager"].items()):
        md.append(f"| {name} | {', '.join(sorted(managers))} |")
    md += [
        "",
        f"Of the {pl['institutions_reached']} institutions this layer reaches, the "
        "table lists those with more than one fund manager. The one the Bank of Ghana "
        "did **not** flag for related-party exposure is "
        f"{', '.join(pl['institutions_unflagged_by_bog']) or 'none'}. Section 4's "
        "comparison is therefore a statement about the Bank of Ghana notice, not "
        "about the record as a whole.",
        "",
        "---",
        "",
        "## What this section does not claim",
        "",
        "- The related-party graph is not shown to be one network. It is "
        f"{s['components']} separate structures, and only one entity, "
        f"{', '.join(h['connect_multiple_institutions']) or 'none'}, connects two "
        "of the 23, and only when both notices are read: the Bank of Ghana records "
        "one institution's exposure to it, and the Securities and Exchange "
        "Commission records it placing funds with another. Neither notice alone "
        "names such an entity, which is what section 1 reported before the second "
        "was read.",
        "- Betweenness centrality and community detection return nothing "
        f"interpretable on a graph in {s['components']} pieces, and the high modularity score "
        "measures that fragmentation rather than any discovered structure.",
        "- The placement layer is not evidence of an insider relationship, and no "
        "figure above treats it as one.",
        "- Amounts are not comparable across institutions. Some are exact, some are "
        "floors, some are totals shared between counterparties, one transfer is "
        "stated in three currencies, and the Commission's figures are percentages of "
        "a fund's own book rather than cedi sums. Only exact cedi amounts on "
        "value-moving edges are summed anywhere above; nothing sums a percentage.",
        "- Nothing here is an allegation. Each edge restates what a regulator "
        "or, in one case, a court published, and the passage behind it is quoted in `data/evidence.csv` with a "
        "line anchor into the source.",
        "- GN Savings and Loans is excluded from the worked examples. The Court of "
        "Appeal quashed the revocation of its licence on 21 May 2026, and the Supreme "
        "Court stayed that judgment on 14 July 2026 pending appeal. Its Bank of Ghana "
        "edges remain, attributed to the Bank; its membership of Groupe Nduom is "
        "attributed to the Court of Appeal.",
    ]
    if pending:
        md.append(f"- {pending} edges are unverified, so every figure is provisional.")

    path.write_text("\n".join(md) + "\n", encoding="utf-8", newline="\n")


def main():
    if not DB.exists():
        raise SystemExit("db/graph.db not found - run python scripts/load.py first")
    con = sqlite3.connect(DB)
    g = load_graph(con)

    metrics = {
        "shape": shape(g),
        "hubs": hubs(g),
        "loops": loops(g),
        "communities": communities(g),
        "typology": typology(con),
        "comparative": comparative(con),
        "placement_layer": placement_layer(con),
        "verification": verification_state(con),
    }

    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "metrics.json").write_text(json.dumps(metrics, indent=2), encoding="utf-8",
                                      newline="\n")
    write_findings(metrics, OUT / "FINDINGS.md")

    s, h = metrics["shape"], metrics["hubs"]
    print(f"nodes {s['nodes']}  edges {s['edges']}  components {s['components']}")
    print(f"betweenness non-zero            : {h['nonzero_betweenness']}")
    print(f"entities touching >1 institution: {len(h['connect_multiple_institutions'])}")
    print(f"cycles                          : {metrics['loops']['count']}")
    print(f"communities == components       : "
          f"{metrics['communities']['communities_equal_components']}")
    print(f"modularity                      : {metrics['communities']['modularity']}")
    pl = metrics["placement_layer"]
    print(f"placement layer (kept separate) : {pl['edges']} edge(s), "
          f"{pl['fund_managers']} fund manager(s), "
          f"{pl['institutions_reached']} of the 23 reached")
    print(f"\nwrote docs/phase2/FINDINGS.md and metrics.json")
    con.close()


if __name__ == "__main__":
    main()
